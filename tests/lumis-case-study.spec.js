import { test, expect } from './browser-test.js';

test('Lumis case study matches hero geometry and works on mobile', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1024 });
  await page.goto('/projects/lumis');
  await page.evaluate(() => document.fonts.ready);
  await expect(page).toHaveTitle('Lumis Dermatologists — Grateful Erhis');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Dermatology without the blind spots');
  const image = page.locator('.lumis-hero-image img');
  await expect.poll(() => image.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  const box = await page.locator('.lumis-hero-image').boundingBox();
  expect(box.x).toBe(273);
  expect(box.y).toBe(168);
  expect(box.width).toBe(1127);
  expect(box.height).toBeCloseTo(626, 0);
  await expect(page.locator('.lumis-heading h1')).toHaveCSS('font-weight', '700');
  await expect(page.locator('.lumis-timeline')).toHaveCSS('font-size', '16px');
  await expect(page.locator('.lumis-section-active')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  await expect(page.locator('.lumis-details dd').first()).toHaveCSS('color', 'rgb(127, 108, 114)');
  await expect(page.locator('.lumis-details dt').first()).toHaveCSS('color', 'rgb(175, 156, 162)');
  await expect(page.locator('.lumis-heading h1')).toHaveCSS('color', 'rgb(74, 59, 64)');
  await expect(page.locator('.lumis-sidebar nav a[aria-current="location"]')).toHaveCount(1);
  await expect(page.locator('#overview')).toHaveCSS('width', '1127px');
  await expect(page.locator('#problem')).toHaveCSS('width', '1127px');
  await expect(page.locator('#opportunity')).toHaveCSS('width', '1127px');
  await expect(page.locator('#solution')).toHaveCSS('width', '1127px');
  const problemImage = page.locator('.lumis-problem-banner > img');
  await expect.poll(() => problemImage.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 600 });
  const sidebarBeforeScroll = await page.locator('.lumis-sidebar').boundingBox();
  await page.evaluate(() => scrollTo(0, 300));
  const sidebarAfterScroll = await page.locator('.lumis-sidebar').boundingBox();
  expect(sidebarAfterScroll.y).toBeCloseTo(sidebarBeforeScroll.y, 1);
  await page.locator('#problem').evaluate(node => node.scrollIntoView({ block: 'start' }));
  await expect(page.locator('.lumis-sidebar a[href="#problem"]')).toHaveAttribute('aria-current', 'location');
  await expect(page.locator('.lumis-sidebar a[href="#problem"]')).toHaveCSS('color', 'rgb(127, 108, 114)');
  await page.locator('#opportunity').evaluate(node => node.scrollIntoView({ block: 'start' }));
  await expect(page.locator('.lumis-sidebar a[href="#opportunity"]')).toHaveAttribute('aria-current', 'location');
  await page.locator('#solution').evaluate(node => node.scrollIntoView({ block: 'start' }));
  await expect(page.locator('.lumis-sidebar a[href="#solution"]')).toHaveAttribute('aria-current', 'location');
  await page.screenshot({ path: 'test-results/lumis-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/lumis-mobile.png', fullPage: true });
  await page.getByRole('link', { name: 'Back', exact: true }).click();
  await expect(page).toHaveURL(/\/projects$/);
  await page.getByRole('link', { name: 'View Lumis Dermatologists case study' }).click();
  await expect(page).toHaveURL(/\/projects\/lumis$/);
  expect(errors).toEqual([]);
});
